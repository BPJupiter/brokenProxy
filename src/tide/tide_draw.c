internal UI_BOX_CUSTOM_DRAW(ti_geo3d_box_draw)
{
    TI_Geo3D_Box_Draw_Data *draw_data = (TI_Geo3D_Box_Draw_Data *)user_data;

    // get clip
    Rng2f32 clip = box->rect;
    for (UI_Box *b = box->parent; !ui_box_is_nil(b); b = b->parent)
    {
        if (b->flags & UI_BoxFlag_Clip)
        {
            clip = intersect_2f32(b->rect, clip);
        }
    }

    // eye/target
    Vec3f32 target = {0};
    Vec3f32 eye = v3f32(draw_data->zoom*cos_f32(draw_data->yaw)*sin_f32(draw_data->pitch),
                        draw_data->zoom*sin_f32(draw_data->yaw)*sin_f32(draw_data->pitch),
                        draw_data->zoom*cos_f32(draw_data->pitch));

    Vec2f32 box_dim = dim_2f32(box->rect);
    R_Pass_Params_Geo3D *pass = dr_geo3d_begin(box->rect,
                                              make_look_at_4x4f32(eye, target, v3f32(0, 0, 1)),
                                              make_perspective_4x4f32(0.25, box_dim.x/box_dim.y, 0.1f, 500.f));
    pass->clip = clip;
    dr_mesh(draw_data->vertex_buffer,
            draw_data->index_buffer,
            R_GeoTopologyKind_Triangles,
            R_GeoVertexFlag_TexCoord|R_GeoVertexFlag_Normals|R_GeoVertexFlag_RGB,
            draw_data->texture,
            mat_4x4f32(1.f));
}

